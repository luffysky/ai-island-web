// 決定性 hash：字串 → 32-bit 正整數
function hash(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
  return (h >>> 0);
}
const pick = <T,>(arr: T[], seed: string): T => arr[hash(seed) % arr.length];


/** 免費・決定性產生某星座某日的運勢（同人同星座同日永遠一樣）。 */
export function generateFreeFortune(zodiac: Zodiac, date: string): FortunePayload {
  const z = ZODIAC_ZH[zodiac];
  const base = `${z}|${date}`;
  return {
    overall: pick(OVERALL, base + "|o"),
    love: pick(LOVE, base + "|l"),
    career: pick(CAREER, base + "|c"),
    wealth: pick(WEALTH, base + "|w"),
    luckyColor: pick(COLORS, base + "|color"),
    luckyNumber: (hash(base + "|num") % 9) + 1,
    tip: pick(TIP, base + "|t"),
    score: 62 + (hash(base + "|score") % 34), // 62–95，偏正向
  };
}
